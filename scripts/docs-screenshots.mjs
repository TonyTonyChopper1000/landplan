// Captures the screenshots used by the in-app Docs (/docs). Run against `vite preview` on :4173.
import { createRequire } from 'node:module';
import { mkdirSync } from 'node:fs';
const { chromium } = createRequire(import.meta.url)('playwright');
const BASE = process.env.APP_URL ?? 'http://localhost:4173';
const OUT = process.env.OUT ?? 'docs-shots';
mkdirSync(OUT, { recursive: true });
const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const shot = (n) => p.screenshot({ path: `${OUT}/${n}.png` });
await p.goto(`${BASE}/`);
await p.waitForTimeout(2800);
await shot('landing');
await p.goto(`${BASE}/projects/new`);
await p.waitForTimeout(800);
await p.getByRole('button', { name: /Residential plots/ }).click();
await p.mouse.move(5, 5);
await p.waitForTimeout(400);
await shot('wizard-type');
await p.getByRole('button', { name: /Continue/ }).click();
await p.getByPlaceholder(/Shamshabad Greens/).fill('Shamshabad Greens Phase 1');
await p.getByPlaceholder(/Shamshabad, Rangareddy/).fill('Shamshabad, Rangareddy');
await p.getByPlaceholder(/Kothwalguda/).fill('Kothwalguda');
await p.getByPlaceholder(/112\/A/).fill('112/A, 113, 114/1');
await p.mouse.move(5, 5);
await shot('wizard-site');
await p.getByRole('button', { name: /Continue/ }).click();
await p.waitForTimeout(300);
await shot('wizard-plan');
await p.getByRole('button', { name: /Continue/ }).click();
await p.waitForTimeout(300);
await shot('wizard-generate');
await p.getByRole('button', { name: /Generate layout/ }).click();
await p.waitForURL(/\/projects\/prj_/, { timeout: 30000 });
await p.waitForTimeout(1800);
await shot('overview');
await p.getByRole('tab', { name: /^Studio/ }).click();
await p.waitForTimeout(1500);
const box = await p.locator('[role=application]').boundingBox();
await p.mouse.move(box.x + box.width * 0.42, box.y + box.height * 0.72);
await p.waitForTimeout(500);
await shot('studio');
// Draw a lake
await p.getByRole('button', { name: 'Constraints', exact: true }).first().click();
await p.getByRole('button', { name: /Lake FTL/ }).click();
const cx = box.x + box.width / 2, cy = box.y + box.height / 2;
for (const [dx, dy] of [[-60, -40], [40, -50], [70, 20], [-10, 60], [-70, 30]]) await p.mouse.click(cx + dx, cy + dy);
await p.keyboard.press('Enter');
await p.waitForTimeout(300);
await p.getByRole('spinbutton', { name: 'Lake area' }).fill('12');
await p.getByRole('spinbutton', { name: 'Lake area' }).press('Enter');
await p.mouse.move(5, 300);
await p.waitForTimeout(1200);
await shot('studio-lake');
await p.getByRole('button', { name: /Optimize/ }).click();
await p.waitForFunction(() => /486\/486/.test(document.querySelector('aside[aria-label=Optimizer]')?.textContent ?? ''), null, { timeout: 30000 });
await p.waitForTimeout(800);
await shot('optimizer');
await p.getByRole('button', { name: 'Close' }).click();
for (const [tab, name, wait] of [['Feasibility', 'feasibility', 900], ['Regulations', 'regulations', 900], ['Schedule', 'schedule', 900], ['Financials', 'financials', 1200], ['3D', '3d', 4000]]) {
  await p.getByRole('tab', { name: new RegExp(`^${tab}`) }).click();
  await p.waitForTimeout(wait);
  await shot(name);
}
await p.getByRole('tab', { name: /^Compare/ }).click();
await p.waitForTimeout(600);
const dup = p.getByRole('button', { name: 'Duplicate current to compare' });
if (await dup.count()) await dup.click();
await p.waitForTimeout(800);
await shot('compare');
await p.getByRole('tab', { name: /^Studio/ }).click();
await p.getByRole('button', { name: 'Export' }).click();
await p.waitForTimeout(1200);
await shot('export');
await p.keyboard.press('Escape');
await p.getByRole('button', { name: 'Close' }).click().catch(() => {});
await p.keyboard.press('Control+k');
await p.waitForTimeout(400);
await shot('palette');
await p.keyboard.press('Escape');
await p.goto(`${BASE}/projects`);
await p.waitForTimeout(1500);
await shot('projects');
await b.close();
console.log('done');
